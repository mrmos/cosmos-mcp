/**
 * Demo GIF, step 2 of 2: render scripts/demo/demo.html to docs/demo.gif.
 *
 * Regenerate the README demo with:
 *
 *   bun run scripts/demo/capture.ts && bun run scripts/demo/render.ts
 *
 * For the second demo, pass the capture file and the output path:
 *
 *   bun run scripts/demo/render.ts scripts/demo/capture-similar.json docs/demo-similar.gif
 *
 * Needs Google Chrome (headless) and ffmpeg; nothing is downloaded. Writes
 * capture.js from capture.json, drives one headless Chrome over the DevTools
 * protocol to screenshot every frame at a fixed 800x500 viewport, then runs
 * ffmpeg's two-pass palettegen/paletteuse to build the GIF.
 *
 * Env overrides: DEMO_FPS (default 12), DEMO_COLORS (default 128),
 * CHROME_PATH, FFMPEG_PATH.
 */
import { mkdtempSync, rmSync, statSync, existsSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dir, "../..");
const DEMO = join(ROOT, "scripts/demo");
// Optional arguments: the capture file and the GIF to write, relative to the repo root.
const capturePath = resolve(ROOT, process.argv[2] ?? "scripts/demo/capture.json");
const OUT = resolve(ROOT, process.argv[3] ?? "docs/demo.gif");
const W = 800, H = 500;
const FPS = Number(process.env.DEMO_FPS ?? 12);
const COLORS = Number(process.env.DEMO_COLORS ?? 128);
const CHROME = process.env.CHROME_PATH ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const FFMPEG = process.env.FFMPEG_PATH ?? Bun.which("ffmpeg") ?? "/opt/homebrew/bin/ffmpeg";

if (!existsSync(capturePath)) throw new Error(`${capturePath} missing: run the capture script first`);
const capture = JSON.parse(readFileSync(capturePath, "utf8"));
await Bun.write(
  join(DEMO, "capture.js"),
  `// Generated by render.ts from capture.json. Do not edit.\nwindow.CAPTURE = ${JSON.stringify(capture)};\n`,
);

const tmp = mkdtempSync(join(tmpdir(), "cosmos-mcp-render-"));
const frames = join(tmp, "frames");
await Bun.$`mkdir -p ${frames}`;

const chrome = Bun.spawn(
  [
    CHROME,
    "--headless=new",
    "--remote-debugging-port=0",
    `--user-data-dir=${join(tmp, "profile")}`,
    "--no-first-run",
    "--no-default-browser-check",
    "--disable-extensions",
    "--hide-scrollbars",
    "--force-color-profile=srgb",
    "--allow-file-access-from-files",
    `--window-size=${W},${H}`,
    "about:blank",
  ],
  { stdout: "ignore", stderr: "ignore" },
);

try {
  // Chrome writes its chosen port to DevToolsActivePort once it is listening.
  const portFile = join(tmp, "profile/DevToolsActivePort");
  let port = 0;
  for (let i = 0; i < 100 && !port; i++) {
    if (existsSync(portFile)) port = Number(readFileSync(portFile, "utf8").split("\n")[0]);
    if (!port) await Bun.sleep(100);
  }
  if (!port) throw new Error("Chrome did not start (no DevToolsActivePort)");

  const targets = (await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()) as any[];
  const page = targets.find((t) => t.type === "page");
  const ws = new WebSocket(page.webSocketDebuggerUrl);
  await new Promise((res, rej) => ((ws.onopen = res), (ws.onerror = rej)));

  let id = 0;
  const waiting = new Map<number, { res: (v: any) => void; rej: (e: Error) => void }>();
  const events = new Map<string, () => void>();
  ws.onmessage = (ev) => {
    const msg = JSON.parse(String(ev.data));
    if (msg.id && waiting.has(msg.id)) {
      const w = waiting.get(msg.id)!;
      waiting.delete(msg.id);
      msg.error ? w.rej(new Error(JSON.stringify(msg.error))) : w.res(msg.result);
    } else if (msg.method && events.has(msg.method)) {
      events.get(msg.method)!();
      events.delete(msg.method);
    }
  };
  const cdp = (method: string, params: object = {}): Promise<any> =>
    new Promise((res, rej) => {
      const i = ++id;
      waiting.set(i, { res, rej });
      ws.send(JSON.stringify({ id: i, method, params }));
    });
  const once = (method: string) => new Promise<void>((res) => events.set(method, res));

  await cdp("Page.enable");
  await cdp("Emulation.setDeviceMetricsOverride", { width: W, height: H, deviceScaleFactor: 1, mobile: false });
  const loaded = once("Page.loadEventFired");
  await cdp("Page.navigate", { url: pathToFileURL(join(DEMO, "demo.html")).href + "?t=0" });
  await loaded;

  const evaluate = async (expression: string) => {
    const r = await cdp("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
    if (r.exceptionDetails) throw new Error(`page error: ${JSON.stringify(r.exceptionDetails)}`);
    return r.result.value;
  };
  // Make sure every tile image has decoded before the first screenshot.
  await evaluate("Promise.all([...document.images].map((i) => i.decode()))");
  const broken = await evaluate("[...document.images].filter((i) => !i.naturalWidth).length");
  if (broken) throw new Error(`${broken} image(s) failed to load`);

  const duration: number = await evaluate("window.DURATION");
  const count = Math.ceil(duration * FPS) + 1;
  console.error(`rendering ${count} frames (${duration.toFixed(2)} s at ${FPS} fps)`);
  for (let f = 0; f < count; f++) {
    const t = Math.min(f / FPS, duration);
    await evaluate(`window.render(${t}); new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))`);
    const shot = await cdp("Page.captureScreenshot", {
      format: "png",
      clip: { x: 0, y: 0, width: W, height: H, scale: 1 },
    });
    await Bun.write(join(frames, `f${String(f).padStart(4, "0")}.png`), Buffer.from(shot.data, "base64"));
  }
  ws.close();

  // Two-pass GIF: one palette for the whole clip, then dither against it.
  const palette = join(tmp, "palette.png");
  const input = ["-framerate", String(FPS), "-i", join(frames, "f%04d.png")];
  await Bun.$`${FFMPEG} -loglevel error -y ${input} -vf palettegen=max_colors=${COLORS}:stats_mode=full ${palette}`;
  await Bun.$`mkdir -p ${join(ROOT, "docs")}`;
  await Bun.$`${FFMPEG} -loglevel error -y ${input} -i ${palette} -lavfi ${"paletteuse=dither=sierra2_4a:diff_mode=rectangle"} -loop 0 ${OUT}`;
  const kb = statSync(OUT).size / 1024;
  console.error(`wrote ${OUT} (${kb.toFixed(0)} KB, ${count} frames)`);
  if (process.env.DEMO_KEEP_FRAMES) console.error(`frames kept in ${frames}`);
} finally {
  chrome.kill();
  await chrome.exited;
  if (!process.env.DEMO_KEEP_FRAMES) rmSync(tmp, { recursive: true, force: true });
}
